const byId = new Map(GUIDE_IMAGES.map((img) => [img.id, img]));

export function guideImageMarkdown(id: number): string {
  const img = byId.get(id);
  if (!img) return "";
  return `\n![${img.alt}](${img.url})\n\n*${img.caption}*\n`;
}

export function injectGuideImages(markdown: string): string {
  return markdown.replace(/\{\{GUIDE_IMAGE:(\d+)\}\}/g, (_, raw) => {
    const id = Number(raw);
    return guideImageMarkdown(id);
  });
}

export function injectGuideCover(markdown: string): string {
  if (!markdown.includes("{{GUIDE_COVER}}")) return markdown;

  const cover = `
<div class="guide-cover">
  <img src="${GUIDE_COVER_URL}" alt="${GUIDE_COVER_ALT.replace(/"/g, "&quot;")}" loading="eager" />
</div>
`.trim();

  return markdown.replace(/\{\{GUIDE_COVER\}\}/g, cover);
}
